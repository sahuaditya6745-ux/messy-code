SUBJECT_COUNT = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def total_score(student_record):
    """Return the sum of a student's numeric scores, skipping the name."""
    score_sum = 0
    for index in range(1, len(student_record)):
        score_sum = score_sum + student_record[index]
    return score_sum


def average_score(student_record):
    """Return the mean of a student's numeric scores."""
    return total_score(student_record) / SUBJECT_COUNT


def count_above_class_average(student_list):
    """Return how many students have an average above the class average."""
    average_sum = 0
    for index in range(0, len(student_list)):
        average_sum = average_sum + average_score(student_list[index])
    class_mean = average_sum / len(student_list)

    above_count = 0
    for index in range(0, len(student_list)):
        if average_score(student_list[index]) > class_mean:
            above_count = above_count + 1
    return above_count


